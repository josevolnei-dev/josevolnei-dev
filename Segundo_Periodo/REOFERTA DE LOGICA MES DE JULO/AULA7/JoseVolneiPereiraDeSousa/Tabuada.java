import java.util.Scanner;

public class Tabuada {

    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);

        System.out.println(" Digite um numero para tabuada");
        int num = sc.nextInt();
        for ( int i = 1; i <= 10 ; i ++){
            System.out.println(" 8 x " + i + "=" + (num * i));

        }

        sc.close();
    }
}
